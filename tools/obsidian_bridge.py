def build_claim_note(card: dict) -> GeneratedFile:
    claim_id = card.get("claim_id") or "UNKNOWN-CLAIM"
    source = card.get("_source_path", "")
    fm = {
        "id": claim_id,
        "tier": card.get("tier"),
        "k_state": card.get("k_state"),
        "spine_stage": card.get("status"),
        "genre": card.get("genre"),
        "produced_by": card.get("produced_by"),
    }
    body = [header(source), "", f"# {claim_id}", ""]
    stmt = _dget(card, "statement", "text")
    if stmt:
        body += ["## Statement", "", str(stmt), ""]
    en = _dget(card, "statement", "translation", "text")
    if en:
        body += ["## Translation", "", str(en), ""]
    five_q_falsifier = _dget(card, "five_questions", "tested", "falsifier")
    if five_q_falsifier:
        body += ["## Five questions — falsifier (Q5)", "", str(five_q_falsifier), ""]
    origin = card.get("origin_blackbox_ref")
    body.append("## Links")
    body.append("")
    if origin:
        bb_id = Path(str(origin).split("#")[0]).stem
        body.append(f"- origin: {wikilink(bb_id)} (`{origin}`)")
    for rel_key, label in (
        ("related_citation_cards", "citation"),
        ("related_source_cards", "source"),
        ("related_observation_cards", "observation"),
    ):
        for ref in card.get(rel_key) or []:
            body.append(f"- {label}: {wikilink(str(ref))}")
    lens_ref = _dget(card, "lens_translation", "lens_ref")
    if lens_ref:
        body.append(f"- lens: {wikilink(LENS_NOTE_TITLE)}")
    body.append("")
    body.append(f"Source of record: `{source}` — this note is a readout, edit the source there.")
    return GeneratedFile(f"claims/{claim_id}.md", frontmatter(fm) + "\n" + "\n".join(body) + "\n")


def build_blackbox_note(note: dict) -> GeneratedFile:
    source = note.get("_source_path", "")
    note_id = note.get("id") or Path(source).stem
    fm = {"id": note_id, "kind": note.get("_kind", "unknown")}
    body = [header(source), "", f"# Blackbox Note {note_id}", ""]
    lens = note.get("lens_used") if isinstance(note.get("lens_used"), dict) else None
    if lens:
        body += ["## Lens used", "", f"- {wikilink(LENS_NOTE_TITLE)}", f"- display: {lens.get('display', '')}", ""]
    lines = note.get("lines")
    if isinstance(lines, list):
        body.append("## Lines (index only — full verbatim text stays in the source file)")
        body.append("")
        for ln in lines:
            if not isinstance(ln, dict):
                continue
            n = ln.get("n")
            speaker = ln.get("speaker")
            kind = ln.get("kind")
            public = ln.get("public")
            body.append(f"- line {n} — {speaker} ({kind}) — public: {public}")
        body.append("")
    body.append(f"Source of record: `{source}`.")
    return GeneratedFile(f"blackbox/{slugify(note_id)}.md", frontmatter(fm) + "\n" + "\n".join(body) + "\n")


def build_kg_note(node: dict, edges: list[dict]) -> GeneratedFile:
    node_id = node.get("id") or "UNKNOWN-NODE"
    fm = {"id": node_id, "type": node.get("type"), "tier": node.get("tier"), "status": node.get("status")}
    body = [header("kg/nodes.jsonl (+ kg/edges.jsonl)"), "", f"# {node.get('label') or node_id}", ""]
    ref = node.get("ref")
    if ref:
        body.append(f"- canonical source: `{ref}`")
    body.append("")
    body.append("## Edges")
    body.append("")
    for e in edges:
        if e.get("from") == node_id:
            body.append(f"- {e.get('relation')} → {wikilink(e.get('to', ''))} (status: {e.get('status')})")
        elif e.get("to") == node_id:
            body.append(f"- ← {e.get('relation')} {wikilink(e.get('from', ''))} (status: {e.get('status')})")
    body.append("")
    return GeneratedFile(f"kg/{slugify(node_id)}.md", frontmatter(fm) + "\n" + "\n".join(body) + "\n")



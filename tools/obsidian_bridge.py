def load_manifest(vault_glosa_dir: Path) -> dict:
    mf = vault_glosa_dir / MANIFEST_NAME
    if mf.is_file():
        try:
            return json.loads(mf.read_text(encoding="utf-8"))
        except Exception:
            return {"version": VERSION, "files": {}}
    return {"version": VERSION, "files": {}}


def save_manifest(vault_glosa_dir: Path, manifest: dict) -> None:
    mf = vault_glosa_dir / MANIFEST_NAME
    mf.write_text(json.dumps(manifest, indent=2, ensure_ascii=False, sort_keys=True) + "\n", encoding="utf-8")


def write_generated(vault_glosa_dir: Path, files: list[GeneratedFile], dry_run: bool) -> dict:
    manifest = load_manifest(vault_glosa_dir)
    new_files: dict[str, str] = {}
    written, unchanged = 0, 0
    for gf in files:
        dest = vault_glosa_dir / gf.rel_path
        digest = sha256_text(gf.content)
        new_files[gf.rel_path] = digest
        if dry_run:
            print(f"  [dry-run] would write {dest} ({'new' if gf.rel_path not in manifest.get('files', {}) else 'refresh'})")
            continue
        dest.parent.mkdir(parents=True, exist_ok=True)
        old = dest.read_text(encoding="utf-8") if dest.is_file() else None
        if old == gf.content:
            unchanged += 1
            continue
        dest.write_text(gf.content, encoding="utf-8")
        written += 1

    stale = set(manifest.get("files", {})) - set(new_files)
    for rel in sorted(stale):
        target = vault_glosa_dir / rel
        if dry_run:
            print(f"  [dry-run] would remove stale generated note {target}")
            continue
        if target.is_file() and "generated by glosa obsidian_bridge" in target.read_text(encoding="utf-8", errors="ignore"):
            target.unlink()

    if not dry_run:
        manifest["version"] = VERSION
        manifest["files"] = new_files
        save_manifest(vault_glosa_dir, manifest)

    print(f"sync: {written} written, {unchanged} unchanged, {len(stale)} stale removed"
          f"{' (dry-run, nothing actually written)' if dry_run else ''}")
    return manifest



def _dget(d: Any, *path, default=None):
    cur = d
    for p in path:
        if not isinstance(cur, dict):
            return default
        cur = cur.get(p, default)
        if cur is None:
            return default
    return cur


def scan_claim_cards() -> list[dict]:
    out = []
    for base in (REPO_ROOT / "paper" / "claims", REPO_ROOT / "cases"):
        if not base.is_dir():
            continue
        for f in sorted(base.glob("*.yaml")):
            data = load_yaml_file(f)
            card = data.get("claim_card") if isinstance(data, dict) else None
            if not isinstance(card, dict):
                continue
            card["_source_path"] = str(f.relative_to(REPO_ROOT))
            out.append(card)
    return out


def scan_blackbox_notes() -> list[dict]:
    out = []
    base = REPO_ROOT / "blackbox"
    if not base.is_dir():
        return out
    for f in sorted(base.iterdir()):
        if f.name in ("README.md",) or f.is_dir():
            continue
        rel = str(f.relative_to(REPO_ROOT))
        if f.suffix in (".yaml", ".yml"):
            data = load_yaml_file(f)
            note = data.get("blackbox_note") if isinstance(data, dict) else data
            if isinstance(note, dict):
                note["_source_path"] = rel
                note["_kind"] = "yaml"
                out.append(note)
        elif f.suffix == ".md":
            out.append({"_source_path": rel, "_kind": "md", "id": f.stem})
    return out


def scan_kg() -> tuple[list[dict], list[dict]]:
    nodes, edges = [], []
    kg_dir = REPO_ROOT / "kg"
    node_file = kg_dir / "nodes.jsonl"
    edge_file = kg_dir / "edges.jsonl"
    if node_file.is_file():
        for line in node_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                nodes.append(json.loads(line))
            except Exception:
                continue
    if edge_file.is_file():
        for line in edge_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line:
                continue
            try:
                edges.append(json.loads(line))
            except Exception:
                continue
    return nodes, edges


def scan_records_lit(root: Path | None = None) -> dict[str, dict]:
    """records/lit/<hypothesis_slug>/ -> {slug: {search_log, citations[], dialogue_table_path,
    litreview_manifest, acquisitions[]}}. Detection is by shape, not fixed filenames, so this
    tolerates whatever real layout the literature-review agent lands on."""
    base = (root or REPO_ROOT) / "records" / "lit"
    result: dict[str, dict] = {}
    if not base.is_dir():
        return result
    for hyp_dir in sorted(p for p in base.iterdir() if p.is_dir()):
        slug = hyp_dir.name
        entry = {
            "dir": hyp_dir, "search_log": None, "citations": [], "acquisitions": [],
            "dialogue_table_path": None, "litreview_manifest": None,
        }
        for f in sorted(hyp_dir.rglob("*")):
            if f.is_dir():
                continue
            if f.suffix == ".md" and "dialogue" in f.name.lower():
                entry["dialogue_table_path"] = f
                continue
            if f.suffix not in (".yaml", ".yml"):
                continue
            data = load_yaml_file(f)
            if not isinstance(data, dict):
                continue
            if "search_mode" in data:
                entry["search_log"] = (f, data)
            elif "identifier" in data and "fetch_status" in data:
                entry["citations"].append((f, data))
            elif "acquisition_route" in data or "acquisition_status" in data:
                entry["acquisitions"].append((f, data))
            elif "gate" in data and "strata_table" in data:
                entry["litreview_manifest"] = (f, data)
        result[slug] = entry
    return result


def scan_hypothesis_selections(root: Path | None = None) -> list[tuple[Path, dict]]:
    out = []
    base = (root or REPO_ROOT) / "records" / "lit"
    if not base.is_dir():
        return out
    for f in base.glob("*.yaml"):
        data = load_yaml_file(f)
        if isinstance(data, dict) and "candidates" in data and "selection" in data:
            out.append((f, data))
    return out



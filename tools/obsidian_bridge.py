def slugify(s: str) -> str:
    s = re.sub(r"[^\w\-\. ]+", "", s, flags=re.UNICODE).strip()
    s = re.sub(r"\s+", "_", s)
    return s or "untitled"


def wikilink(title: str) -> str:
    return f"[[{title}]]"


def header(source_rel: str) -> str:
    return GENERATED_HEADER.format(version=VERSION, source=source_rel)


def sha256_text(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def frontmatter(fields: dict[str, Any]) -> str:
    lines = ["---"]
    for k, v in fields.items():
        if isinstance(v, list):
            if not v:
                lines.append(f"{k}: []")
            else:
                lines.append(f"{k}:")
                for item in v:
                    lines.append(f"  - {_fm_scalar(item)}")
        else:
            lines.append(f"{k}: {_fm_scalar(v)}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def _fm_scalar(v: Any) -> str:
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    s = str(v)
    if any(c in s for c in [":", "#", "\n"]) or s.strip() != s:
        return json.dumps(s, ensure_ascii=False)
    return s


class GeneratedFile:
    __slots__ = ("rel_path", "content")

    def __init__(self, rel_path: str, content: str):
        self.rel_path = rel_path
        self.content = content



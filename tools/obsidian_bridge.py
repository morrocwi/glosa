class VaultInfo:
    def __init__(self, mode: str, path: Path | None, reason: str):
        self.mode = mode  # "env" | "profile" | "self" | "none"
        self.path = path
        self.reason = reason

    def __repr__(self) -> str:
        return f"VaultInfo(mode={self.mode!r}, path={self.path}, reason={self.reason!r})"


def _author_profile_vault() -> Path | None:
    profile_path = Path(os.path.expanduser("~/.config/glosa/author_profile.json"))
    if not profile_path.exists():
        return None
    try:
        data = json.loads(profile_path.read_text(encoding="utf-8"))
    except Exception:
        return None
    val = (data.get("defaults") or {}).get("obsidian_vault")
    if not val:
        return None
    return Path(os.path.expanduser(str(val)))


def detect() -> VaultInfo:
    """Vault resolution order: env -> author_profile -> self. Never raises."""
    if os.environ.get("GLOSA_OBSIDIAN_DISABLE") == "1":
        return VaultInfo("none", None, "GLOSA_OBSIDIAN_DISABLE=1 set — bridge explicitly disabled")

    env_val = os.environ.get("GLOSA_OBSIDIAN_VAULT")
    if env_val is not None:
        if env_val.strip().lower() in ("", "none"):
            return VaultInfo("none", None, "GLOSA_OBSIDIAN_VAULT explicitly empty/none")
        p = Path(os.path.expanduser(env_val)).resolve()
        if p.is_dir():
            return VaultInfo("env", p, f"GLOSA_OBSIDIAN_VAULT={p}")
        return VaultInfo("none", None, f"GLOSA_OBSIDIAN_VAULT={env_val} does not exist — no vault, bridge skipped")

    profile_vault = _author_profile_vault()
    if profile_vault is not None:
        if profile_vault.is_dir():
            return VaultInfo("profile", profile_vault.resolve(),
                              f"author_profile.json defaults.obsidian_vault={profile_vault}")
        return VaultInfo("none", None,
                          f"author_profile.json names {profile_vault} but it does not exist — bridge skipped")

    # self mode: the glosa repo itself, opened as a vault at <repo>/obsidian/
    self_path = (REPO_ROOT / "obsidian").resolve()
    return VaultInfo("self", self_path, "no env/profile vault configured — using glosa repo itself as the vault "
                                          "(self mode; open the glosa repo root in Obsidian)")


def cmd_detect(args: argparse.Namespace) -> int:
    info = detect()
    print(f"glosa obsidian_bridge v{VERSION} (yaml backend: {_YAML_BACKEND})")
    if info.mode == "none":
        print("no vault — bridge skipped")
        print(f"  reason: {info.reason}")
        return 0
    print(f"vault mode: {info.mode}")
    print(f"vault path: {info.path}")
    print(f"reason: {info.reason}")
    has_dot_obsidian = (info.path / ".obsidian").is_dir() if info.path else False
    print(f".obsidian present at vault root: {has_dot_obsidian}")
    return 0



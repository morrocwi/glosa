    body.append("")
    body.append("_Obsidian is an analysis surface for this repo's own files — the graph and "
                "backlinks help a human SEE clusters (agree/disagree, concentration, orphans); it "
                "is never the source of truth. The source of truth is always the file named in "
                "each note's header._")

    return GeneratedFile("00_INDEX.md", "\n".join(body) + "\n")



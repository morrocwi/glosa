def build_hypothesis_note(slug: str, entry: dict) -> GeneratedFile:
    fm = {"id": slug}
    body = [header(f"records/lit/{slug}/"), "", f"# Hypothesis: {slug}", ""]
    sl = entry.get("search_log")
    if sl:
        f, data = sl
        body.append(f"- search_log: `{f.relative_to(REPO_ROOT)}` (mode: {data.get('search_mode')})")
    lm = entry.get("litreview_manifest")
    if lm:
        f, data = lm
        gate = data.get("gate") or {}
        body.append(f"- litreview_manifest: `{f.relative_to(REPO_ROOT)}` "
                     f"(accuracy_gate: {gate.get('accuracy_gate')}, diversity_gate: {gate.get('diversity_gate')}, "
                     f"overall: {gate.get('overall')})")
    dt = entry.get("dialogue_table_path")
    if dt:
        body.append(f"- dialogue_table: `{dt.relative_to(REPO_ROOT)}`")
    body.append("")
    body.append("## Sources")
    body.append("")
    for f, cdata in entry.get("citations", []):
        cid = cdata.get("id") or f.stem
        body.append(f"- {wikilink(cid)}")
    body.append("")
    body.append("Backlinks (agree/disagree clusters, orphans, concentration) show up in Obsidian's "
                 "own graph/backlink panel once source notes below link here and to each other — "
                 "this bridge only writes the links, Obsidian renders the graph.")
    return GeneratedFile(f"records_lit/{slugify(slug)}/00_hypothesis.md",
                          frontmatter(fm) + "\n" + "\n".join(body) + "\n")


def build_source_note(slug: str, hyp_slug: str, cdata: dict, source_rel: str,
                       all_citations: list[dict]) -> GeneratedFile:
    cid = cdata.get("id") or slug
    dialogue_stance = None  # filled in by caller if a dialogue_table row is matched; kept generic here
    fm = {
        "source_id": cid,
        "stance": cdata.get("_stance", "undetermined"),
        "region": _dget(cdata, "_diversity", "geography_or_institution") or "",
        "language": _dget(cdata, "_diversity", "language") or "",
        "source_type": _dget(cdata, "_diversity", "source_type") or "",
        "venue_quality_index": _dget(cdata, "_diversity", "venue_quality_index", "value"),
        "verified": bool(cdata.get("status") == "VERIFIED"),
    }
    body = [header(source_rel), "", f"# {cid}", ""]
    body.append(f"- hypothesis: {wikilink(hyp_slug)}")
    ident = cdata.get("identifier") or {}
    if ident:
        body.append(f"- identifier: {ident.get('kind')} {ident.get('value')}")
    body.append(f"- fetch_status: {cdata.get('fetch_status')}")
    body.append(f"- status: {cdata.get('status')}")
    stance = fm["stance"]
    for other in all_citations:
        other_id = other.get("id")
        if not other_id or other_id == cid:
            continue
        other_stance = other.get("_stance")
        if other_stance and other_stance == stance and stance in ("agree", "disagree"):
            body.append(f"- {stance}s-with-cluster: {wikilink(other_id)}")
    body.append("")
    return GeneratedFile(f"records_lit/{slugify(hyp_slug)}/sources/{slugify(cid)}.md",
                          frontmatter(fm) + "\n" + "\n".join(body) + "\n")


def build_hypothesis_selection_note(f: Path, data: dict) -> GeneratedFile:
    hid = data.get("id") or f.stem
    fm = {"id": hid, "decided_by": data.get("decided_by"), "decided_at": data.get("decided_at")}
    body = [header(str(f.relative_to(REPO_ROOT))), "", f"# Hypothesis selection {hid}", ""]
    sel = data.get("selection") or {}
    chosen = sel.get("chosen") or []
    body.append("## Chosen")
    body.append("")
    for c in chosen:
        body.append(f"- {wikilink(str(c))}")
    body.append("")
    body.append("## Parked")
    body.append("")
    for p in sel.get("parked") or []:
        if isinstance(p, dict):
            body.append(f"- {wikilink(str(p.get('hypothesis_ref')))} — {p.get('reason', '')}")
    body.append("")
    return GeneratedFile("records_lit/00_hypothesis_selection.md",
                          frontmatter(fm) + "\n" + "\n".join(body) + "\n")



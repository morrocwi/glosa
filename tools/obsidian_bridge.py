def cmd_check(args: argparse.Namespace) -> int:
    if args.vault:
        info = VaultInfo("cli", Path(os.path.expanduser(args.vault)).resolve(), f"--vault {args.vault}")
    else:
        info = detect()

    print(f"vault mode: {info.mode}")
    if info.mode == "none" or info.path is None:
        print("no vault — bridge skipped (nothing to check)")
        return 0

    vault_glosa_dir = info.path / "glosa"
    print(f"vault path: {info.path}")
    print(f"glosa subdir present: {vault_glosa_dir.is_dir()}")
    if not vault_glosa_dir.is_dir():
        return 0

    manifest = load_manifest(vault_glosa_dir)
    files = manifest.get("files", {})
    print(f"generated files tracked in manifest: {len(files)}")

    all_titles = set()
    for rel in files:
        all_titles.add(Path(rel).stem)

    dangling = []
    link_re = re.compile(r"\[\[([^\]|#]+)")
    for rel in files:
        p = vault_glosa_dir / rel
        if not p.is_file():
            continue
        for m in link_re.finditer(p.read_text(encoding="utf-8", errors="ignore")):
            target = m.group(1).strip()
            if target not in all_titles:
                dangling.append((rel, target))

    print(f"dangling wikilinks: {len(dangling)}")
    for rel, target in dangling[:50]:
        print(f"  [DANGLING] {rel} -> [[{target}]]")
    return 0



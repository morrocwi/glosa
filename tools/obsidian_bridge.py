TAG_RE = re.compile(r"#([A-Za-z0-9_/\-]+)")


def cmd_harvest(args: argparse.Namespace) -> int:
    if args.vault:
        info = VaultInfo("cli", Path(os.path.expanduser(args.vault)).resolve(), f"--vault {args.vault}")
    else:
        info = detect()
    if info.mode == "none" or info.path is None:
        print("no vault — bridge skipped")
        return 0

    vault_glosa_dir = info.path / "glosa"
    lit_dir = vault_glosa_dir / "records_lit"
    if not lit_dir.is_dir():
        print("no records_lit/ notes under this vault — nothing to harvest")
        return 0

    manifest = load_manifest(vault_glosa_dir)
    known_files = set(manifest.get("files", {}))

    harvested_by_hyp: dict[str, list[dict]] = {}
    for src_note in lit_dir.glob("*/sources/*.md"):
        rel = str(src_note.relative_to(vault_glosa_dir))
        text = src_note.read_text(encoding="utf-8", errors="ignore")
        header_marker = "generated by glosa obsidian_bridge"
        # split off the generated header block; anything a human appended after it (or a tag
        # anywhere in the body) is a harvest candidate — we never assume the header lines are
        # human content.
        body_after_header = text.split(header_marker, 1)[-1]
        tags = sorted(set(TAG_RE.findall(body_after_header)))
        if not tags:
            continue
        hyp_slug = src_note.parent.parent.name
        source_id = src_note.stem
        harvested_by_hyp.setdefault(hyp_slug, []).append({
            "source_id": source_id,
            "note_path": rel,
            "tags_found": tags,
            "candidate_edits": _tags_to_candidate_edits(tags),
        })

    if not harvested_by_hyp:
        print("no human-added tags found in generated source notes — nothing to harvest")
        return 0

    for hyp_slug, rows in harvested_by_hyp.items():
        out_dir = REPO_ROOT / "records" / "lit" / hyp_slug
        out_path = out_dir / "obsidian_harvest.yaml"
        content = _render_harvest_yaml(hyp_slug, rows)
        if args.dry_run:
            print(f"[dry-run] would write {out_path}:")
            print(content)
            continue
        out_dir.mkdir(parents=True, exist_ok=True)
        out_path.write_text(content, encoding="utf-8")
        print(f"wrote candidate edits: {out_path} ({len(rows)} source(s) with tags)")

    print("These are CANDIDATE edits only — no source YAML was modified. "
          "A human must review obsidian_harvest.yaml and apply confirmed edits by hand.")
    return 0


def _tags_to_candidate_edits(tags: list[str]) -> list[dict]:
    edits = []
    for t in tags:
        if t.startswith("disagrees_"):
            edits.append({"field": "dialogue_table_stance", "candidate_value": "disagrees",
                          "note": f"from tag #{t}"})
        elif t.startswith("agrees_"):
            edits.append({"field": "dialogue_table_stance", "candidate_value": "agrees",
                          "note": f"from tag #{t}"})
        elif t.startswith("region/"):
            edits.append({"field": "diversity.geography_or_institution", "candidate_value": t.split("/", 1)[1],
                          "note": f"from tag #{t}"})
        elif t.startswith("language/") or t.startswith("lang/"):
            edits.append({"field": "diversity.language", "candidate_value": t.split("/", 1)[1],
                          "note": f"from tag #{t}"})
        else:
            edits.append({"field": None, "candidate_value": None, "note": f"unrecognized tag #{t} — human judgement needed"})
    return edits


def _render_harvest_yaml(hyp_slug: str, rows: list[dict]) -> str:
    lines = [
        f"# obsidian_harvest.yaml — CANDIDATE edits harvested from human tags in Obsidian,",
        f"# generated by tools/obsidian_bridge.py harvest for hypothesis '{hyp_slug}'.",
        "# These are proposals only. A human confirms and applies them by hand to the real",
        "# citation_card.yaml / dialogue_table.md — this file never gets auto-applied.",
        f"hypothesis: {hyp_slug}",
        "harvested_at_tool_version: " + VERSION,
        "sources:",
    ]
    for row in rows:
        lines.append(f"  - source_id: {row['source_id']}")
        lines.append(f"    note_path: {row['note_path']}")
        lines.append(f"    tags_found: {json.dumps(row['tags_found'], ensure_ascii=False)}")
        lines.append("    candidate_edits:")
        for e in row["candidate_edits"]:
            lines.append(f"      - field: {e['field']}")
            lines.append(f"        candidate_value: {json.dumps(e['candidate_value'], ensure_ascii=False)}")
            lines.append(f"        note: {json.dumps(e['note'], ensure_ascii=False)}")
        lines.append("    confirmed: false   # human sets true after manually applying to the source file")
    return "\n".join(lines) + "\n"



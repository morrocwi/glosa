#!/usr/bin/env python3
"""
glosa/tools/obsidian_bridge.py — OPTIONAL Obsidian bridge for the glosa repo.

Founder rule, verbatim (2026-09-04): "เชื่อมกับระบบ Obsidian ได้เลย มีก็เชื่อม ไม่มีก็ไม่เชื่อม"
(connect to Obsidian if one exists; if not, do nothing). This tool NEVER fails a build, a
render, or a CI check because a vault is absent — every command below degrades to a clean,
explicit "no vault — bridge skipped" and exit 0 when no vault is configured.

Readout discipline: this bridge renders a VIEW of files that already exist in the repo
(paper/claims/*.yaml, blackbox/*, kg/*.jsonl, records/lit/<hypothesis>/*, registry/, methodology/,
incidents/). It never changes the tier, status, or content of a source file. Every generated note
carries a header saying so and naming the source file to edit instead. A human editing tags/links
directly in Obsidian is captured only via `harvest`, and only as a CANDIDATE file the human must
confirm — this bridge never silently rewrites a source YAML.

Stdlib only. PyYAML is used if imported successfully; otherwise a small best-effort YAML-subset
reader (`_yaml_load`) is used instead (documented limits below). No network calls anywhere.

Commands
--------
    obsidian_bridge.py detect
    obsidian_bridge.py sync [--vault PATH] [--dry-run]
    obsidian_bridge.py check [--vault PATH]
    obsidian_bridge.py harvest [--vault PATH] [--dry-run]
    obsidian_bridge.py unlink [--vault PATH]

Vault resolution order (see `detect()`):
    1. env var GLOSA_OBSIDIAN_VAULT (a path; "none"/"" disables the bridge outright)
    2. ~/.config/glosa/author_profile.json -> defaults.obsidian_vault
    3. "self" mode — the glosa repo's own working tree, treated as a vault at
       <repo>/obsidian/ (Obsidian can open any folder; this is the always-available fallback).
       Self mode can be turned off with GLOSA_OBSIDIAN_DISABLE=1 (then "no vault — bridge skipped").

Never touched by this tool: `.obsidian/` (Obsidian's own app config — appearance, plugins,
workspace layout). This bridge only ever reads/writes inside `<vault>/glosa/`.
"""

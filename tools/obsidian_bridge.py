def cmd_unlink(args: argparse.Namespace) -> int:
    if args.vault:
        info = VaultInfo("cli", Path(os.path.expanduser(args.vault)).resolve(), f"--vault {args.vault}")
    else:
        info = detect()
    if info.mode == "none" or info.path is None:
        print("no vault — bridge skipped")
        return 0

    vault_glosa_dir = info.path / "glosa"
    if not vault_glosa_dir.is_dir():
        print("nothing to unlink — no glosa/ subdir in this vault")
        return 0

    manifest = load_manifest(vault_glosa_dir)
    files = manifest.get("files", {})
    removed = 0
    for rel in sorted(files):
        p = vault_glosa_dir / rel
        if p.is_file() and "generated by glosa obsidian_bridge" in p.read_text(encoding="utf-8", errors="ignore"):
            p.unlink()
            removed += 1
    # prune now-empty directories
    for d in sorted(vault_glosa_dir.rglob("*"), key=lambda p: -len(str(p))):
        if d.is_dir():
            try:
                d.rmdir()
            except OSError:
                pass
    mf = vault_glosa_dir / MANIFEST_NAME
    if mf.is_file():
        mf.unlink()
    print(f"unlink: removed {removed} bridge-generated file(s) from {vault_glosa_dir}")
    return 0



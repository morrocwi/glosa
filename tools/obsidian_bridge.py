def cmd_sync(args: argparse.Namespace) -> int:
    if args.vault:
        vault_path = Path(os.path.expanduser(args.vault)).resolve()
        info = VaultInfo("cli", vault_path, f"--vault {vault_path}")
    else:
        info = detect()

    if info.mode == "none" or info.path is None:
        print("no vault — bridge skipped")
        print(f"  reason: {info.reason}")
        return 0

    vault_glosa_dir = info.path / "glosa"
    if not args.dry_run:
        vault_glosa_dir.mkdir(parents=True, exist_ok=True)
    print(f"sync target: {vault_glosa_dir} (mode: {info.mode})")

    claims = scan_claim_cards()
    blackbox = scan_blackbox_notes()
    nodes, edges = scan_kg()
    lit = scan_records_lit()
    hyp_selections = scan_hypothesis_selections()

    files: list[GeneratedFile] = []
    files.append(build_index(claims, blackbox, nodes, lit, hyp_selections, info))
    for c in claims:
        files.append(build_claim_note(c))
    for n in blackbox:
        files.append(build_blackbox_note(n))
    for n in nodes:
        files.append(build_kg_note(n, edges))
    if claims or nodes or lit:
        files.append(build_lens_stub_note())

    for slug, entry in lit.items():
        files.append(build_hypothesis_note(slug, entry))
        cdatas = []
        for f, cdata in entry.get("citations", []):
            stance = None
            dt = entry.get("dialogue_table_path")
            if dt and dt.is_file():
                stance = _guess_stance_from_dialogue_table(dt.read_text(encoding="utf-8", errors="ignore"),
                                                             cdata.get("id", ""))
            cdata = dict(cdata)
            cdata["_stance"] = stance or "undetermined"
            cdatas.append(cdata)
        for (f, _orig), cdata in zip(entry.get("citations", []), cdatas):
            files.append(build_source_note(f.stem, slug, cdata, str(f.relative_to(REPO_ROOT)), cdatas))

    for f, data in hyp_selections:
        files.append(build_hypothesis_selection_note(f, data))

    write_generated(vault_glosa_dir, files, args.dry_run)
    return 0


def _guess_stance_from_dialogue_table(text: str, citation_id: str) -> str | None:
    if not citation_id:
        return None
    # Column-position heuristic against templates/knowledge/dialogue_table.md's fixed header:
    # | source | how it sees | what it separates | what it assumes | agrees with H | disagrees with H | ... | citation_card | verified |
    for line in text.splitlines():
        if "|" not in line or citation_id not in line:
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 8:
            continue
        agrees, disagrees = cells[4].upper(), cells[5].upper()
        if agrees == "YES":
            return "agree"
        if disagrees == "YES":
            return "disagree"
        if agrees == "ORTHOGONAL" or disagrees == "ORTHOGONAL":
            return "orthogonal"
    return None



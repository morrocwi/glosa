# --------------------------------------------------------------------------
# Minimal YAML-subset reader (used only if PyYAML is not importable)
# --------------------------------------------------------------------------
try:
    import yaml as _pyyaml  # type: ignore

    def _yaml_load(text: str) -> Any:
        return _pyyaml.safe_load(text)

    _YAML_BACKEND = "pyyaml"
except Exception:  # pragma: no cover - exercised on machines without pyyaml
    _YAML_BACKEND = "builtin-subset"

    def _scalar(tok: str) -> Any:
        tok = tok.strip()
        if tok == "" :
            return None
        if tok in ("null", "~", "Null", "NULL"):
            return None
        if tok in ("true", "True", "TRUE"):
            return True
        if tok in ("false", "False", "FALSE"):
            return False
        if len(tok) >= 2 and tok[0] == tok[-1] and tok[0] in ("'", '"'):
            return tok[1:-1]
        if tok == "[]":
            return []
        if tok == "{}":
            return {}
        if tok.startswith("[") and tok.endswith("]"):
            inner = tok[1:-1].strip()
            if not inner:
                return []
            return [_scalar(p) for p in _split_flow(inner)]
        try:
            if re.fullmatch(r"[+-]?\d+", tok):
                return int(tok)
            if re.fullmatch(r"[+-]?\d*\.\d+", tok):
                return float(tok)
        except Exception:
            pass
        return tok

    def _split_flow(inner: str) -> list[str]:
        parts, depth, cur = [], 0, ""
        for ch in inner:
            if ch in "[{":
                depth += 1
            elif ch in "]}":
                depth -= 1
            if ch == "," and depth == 0:
                parts.append(cur)
                cur = ""
            else:
                cur += ch
        if cur.strip():
            parts.append(cur)
        return parts

    def _strip_full_line_comment(line: str) -> str:
        # Only strips a comment that starts a line after optional whitespace, or is clearly
        # preceded by whitespace and not inside a quote. Good enough for the clean, comment-light
        # instance files this bridge actually parses (templates, which are comment-heavy, are
        # never parsed as data by this tool — only referenced for field names in code/docs).
        if re.match(r"^\s*#", line):
            return ""
        m = re.search(r"\s+#(?![^'\"]*['\"]\s*$)", line)
        return line

    def _yaml_load(text: str) -> Any:
        lines = [l.rstrip("\n") for l in text.split("\n")]
        clean: list[tuple[int, str]] = []
        for raw in lines:
            if re.match(r"^\s*#", raw) or not raw.strip():
                continue
            indent = len(raw) - len(raw.lstrip(" "))
            clean.append((indent, raw.strip()))

        pos = [0]

        def parse_block(min_indent: int) -> Any:
            if pos[0] >= len(clean):
                return None
            indent, content = clean[pos[0]]
            if indent < min_indent:
                return None
            if content.startswith("- "):
                items = []
                base_indent = indent
                while pos[0] < len(clean) and clean[pos[0]][0] == base_indent and clean[pos[0]][1].startswith("- "):
                    _, c = clean[pos[0]]
                    rest = c[2:]
                    pos[0] += 1
                    if ":" in rest and not rest.strip().startswith(("'", '"')):
                        key, _, val = rest.partition(":")
                        sub = {}
                        val = val.strip()
                        if val == "":
                            nxt = parse_block(base_indent + 1)
                            sub[key.strip()] = nxt
                        else:
                            sub[key.strip()] = _scalar(val)
                        while pos[0] < len(clean) and clean[pos[0]][0] > base_indent:
                            k2, c2 = clean[pos[0]]
                            if c2.startswith("- "):
                                break
                            key2, _, val2 = c2.partition(":")
                            pos[0] += 1
                            val2 = val2.strip()
                            if val2 == "":
                                sub[key2.strip()] = parse_block(k2 + 1)
                            else:
                                sub[key2.strip()] = _scalar(val2)
                        items.append(sub)
                    else:
                        items.append(_scalar(rest))
                return items
            else:
                mapping: dict[str, Any] = {}
                base_indent = indent
                while pos[0] < len(clean) and clean[pos[0]][0] == base_indent:
                    _, c = clean[pos[0]]
                    if c.startswith("- "):
                        break
                    key, sep, val = c.partition(":")
                    if not sep:
                        pos[0] += 1
                        continue
                    pos[0] += 1
                    val = val.strip()
                    if val in ("|", ">"):
                        block_lines = []
                        while pos[0] < len(clean) and clean[pos[0]][0] > base_indent:
                            block_lines.append(clean[pos[0]][1])
                            pos[0] += 1
                        mapping[key.strip()] = "\n".join(block_lines) if val == "|" else " ".join(block_lines)
                    elif val == "":
                        if pos[0] < len(clean) and clean[pos[0]][0] > base_indent:
                            mapping[key.strip()] = parse_block(base_indent + 1)
                        else:
                            mapping[key.strip()] = None
                    else:
                        # Plain multi-line scalar continuation: YAML folds a bare (unquoted,
                        # non "|"/">"）scalar's following, more-indented lines into the same
                        # value (space-joined) as long as they don't look like a new mapping
                        # key or a list item — this is common in this repo's hand-written YAML
                        # (long statement/description text wrapped across lines with no `|`).
                        pieces = [val] if not (val.startswith(("'", '"'))) else None
                        scalar_val = _scalar(val)
                        if pieces is not None and isinstance(scalar_val, str):
                            while pos[0] < len(clean) and clean[pos[0]][0] > base_indent:
                                cont = clean[pos[0]][1]
                                if cont.startswith("- ") or re.match(r"^[\w.\-]+:( |$)", cont):
                                    break
                                pieces.append(cont)
                                pos[0] += 1
                            scalar_val = " ".join(pieces)
                        mapping[key.strip()] = scalar_val
                return mapping

        return parse_block(0)


def load_yaml_file(path: Path) -> Any:
    try:
        return _yaml_load(path.read_text(encoding="utf-8"))
    except Exception as exc:
        return {"_parse_error": str(exc), "_path": str(path)}


